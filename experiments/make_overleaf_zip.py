"""
Build a self-contained Overleaf bundle for the paper.

    python experiments\\make_overleaf_zip.py      (from the project root)

Output: paper/RBurstHADS_overleaf.zip, holding

    main.tex                 <- paper/paper.tex, byte for byte
    tables_generated.tex     <- the generated appendix tables
    fig/*.pdf                <- the six figures, at the paths main.tex uses
    README.txt

main.tex is a verbatim copy, and the figures keep the `fig/` prefix the paper
already writes, so nothing inside the bundle is rewritten and what compiles on
Overleaf is what is committed here.

The zip itself is deliberately NOT tracked by git (owner's file).
"""
import sys
import zipfile
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAPER = ROOT / "paper"
OUT = PAPER / "RBurstHADS_overleaf.zip"

FIGS = ["fig1_cost_vs_df.pdf", "fig2_makespan_vs_df.pdf", "fig3_cost_vs_scenario.pdf",
        "fig4_makespan_vs_scenario.pdf", "fig5_cost_vs_n.pdf", "fig6_makespan_vs_n.pdf"]

README = """R-BurstHADS -- Overleaf bundle
Built {when} by experiments/make_overleaf_zip.py from the frozen simulator
at tag freeze-fix21 (code fingerprint 2439a00d7f74).

Contents
  main.tex               the paper (a verbatim copy of paper/paper.tex)
  tables_generated.tex   appendix tables, generated by
                         experiments/make_paper_tables.py from DEVIATIONS.md
                         and the committed sweeps -- do not edit by hand
  fig/                   the six figures, as PDF (already 3.40 in wide:
                         include them with no width= option)

Compiling
  pdfLaTeX, twice. The second pass resolves the longtable column widths in the
  per-cell appendix and the cross-references. Document class IEEEtran
  (conference), which Overleaf provides; packages: cite, amsmath, amssymb,
  algorithm, algorithmic, graphicx, booktabs, multirow, longtable, textcomp,
  url.

Regenerating
  python experiments/results_pack.py --fp 2439a00d7f74 --tag freeze-fix21 --val fix21
  python experiments/make_figures.py
  python experiments/make_paper_tables.py
  python experiments/make_overleaf_zip.py
  Every number in the figures and the appendix comes from RESULTS_PACK.md,
  which is generated from committed result files only.

Figures
  All six plot absolute values -- three real series, seconds and dollars, y
  axis from zero. Percentage changes live in the tables, never in a chart.
  See experiments/FIGURE_SPEC.md.
"""


def main():
    missing = [f for f in FIGS if not (PAPER / "fig" / f).exists()]
    for extra in ("paper.tex", "tables_generated.tex"):
        if not (PAPER / extra).exists():
            missing.append(extra)
    if missing:
        raise SystemExit("missing, build them first: " + ", ".join(missing))

    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("main.tex", (PAPER / "paper.tex").read_text(encoding="utf-8"))
        z.writestr("tables_generated.tex", (PAPER / "tables_generated.tex").read_text(encoding="utf-8"))
        for f in FIGS:
            z.write(PAPER / "fig" / f, f"fig/{f}")
        z.writestr("README.txt", README.format(when=date.today().isoformat()))
    names = zipfile.ZipFile(OUT).namelist()
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB, {len(names)} entries)")
    for n in names:
        print(f"  {n}")


if __name__ == "__main__":
    main()
